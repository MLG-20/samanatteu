-- V12 : l'inscription d'une gestionnaire avec vérification de l'email et essai.
--
-- Parcours : elle choisit une formule et s'inscrit → son email n'est PAS vérifié
-- (connexion refusée) → elle clique le lien reçu → email vérifié + abonnement
-- ESSAI de 30 jours sur la formule choisie.
--
-- Le statut ESSAI de l'abonnement ne demande rien ici : la colonne statut est un
-- varchar sans CHECK (l'enum Java fait foi).

-- 1) L'email a-t-il été vérifié ?
-- DEFAULT true : tous les comptes existants sont considérés comme vérifiés (créés
-- avant cette règle, ou par l'admin, ou membres). Seule l'inscription publique
-- d'une gestionnaire écrit false.
ALTER TABLE utilisateur ADD COLUMN email_verifie boolean NOT NULL DEFAULT true;

-- 2) Les liens de vérification envoyés par email.
-- jeton_hache : l'empreinte SHA-256 du jeton (64 caractères hexadécimaux), jamais
-- le jeton lui-même : lire la base ne donne pas de lien utilisable. Contrairement à
-- BCrypt (sel aléatoire), SHA-256 donne toujours la même empreinte : on retrouve la
-- ligne à partir du jeton reçu. UNIQUE : un index, et aucun doublon possible.
-- formule_id : la formule choisie à l'inscription, appliquée à l'essai quand le
-- lien est cliqué.
CREATE TABLE verification_email (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id bigint NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
    formule_id bigint NOT NULL REFERENCES formule (id),
    jeton_hache varchar(64) NOT NULL UNIQUE,
    expire_at timestamp NOT NULL,
    utilise boolean NOT NULL DEFAULT false,
    created_at timestamp NOT NULL,
    updated_at timestamp
);
