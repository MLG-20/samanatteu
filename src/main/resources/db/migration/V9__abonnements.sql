-- Les abonnements : c'est la GESTIONNAIRE qui paie (le modèle SaaS), pas les membres.
--
-- Un abonnement est rattaché à une gestionnaire, PAS à une tontine : une cliente
-- qui gère 10 tontines a UN abonnement.
--
-- La colonne "statut" ne porte que les décisions de la plateforme (ACTIF,
-- SUSPENDU, RESILIE). L'EXPIRATION n'est pas un statut : elle se calcule sur
-- la date de fin (Abonnement.estActif()). Aucun job ne peut donc être en
-- retard, et l'état affiché est toujours juste.
--
-- "sms_envoyes_mois" + "mois_compteur" : compteur remis à zéro chaque mois
-- (le maximum vient de la formule). Stocké dès maintenant, appliqué plus tard.
CREATE TABLE abonnement (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    utilisateur_id bigint NOT NULL REFERENCES utilisateur (id) ON DELETE CASCADE,
    formule character varying(20) NOT NULL,
    statut character varying(20) NOT NULL,
    date_debut date NOT NULL,
    date_fin date NOT NULL,
    sms_envoyes_mois integer NOT NULL DEFAULT 0,
    mois_compteur integer NOT NULL DEFAULT 0,

    -- Un client ne peut avoir qu'UN abonnement en cours : pas de doublon
    -- qui rendrait la règle "quel abonnement s'applique ?" ambiguë.
    CONSTRAINT abonnement_utilisateur_unique UNIQUE (utilisateur_id)
);
