-- Les formules d'abonnement deviennent des DONNÉES, plus des constantes du code.
--
-- Pourquoi : l'ADMIN doit pouvoir changer les quotas et les prix depuis son
-- dashboard, sans redéployer l'application. Un enum dans le code oblige à
-- compiler et redéployer pour changer un prix.
--
-- "nb_*_max = 0" veut dire "sans plafond" (formule MAX).
--
-- 1) La table des formules.
CREATE TABLE formule (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom character varying(30) NOT NULL,
    -- 0 = sans plafond.
    nb_tontines_max integer NOT NULL DEFAULT 0,
    nb_membres_max integer NOT NULL DEFAULT 0,
    sms_par_mois integer NOT NULL DEFAULT 0,
    -- Prix mensuel en FCFA. 0 = "sur devis" (formule MAX).
    prix_mensuel numeric(10,2) NOT NULL DEFAULT 0,
    -- Une formule retirée de la vente reste en base (les abonnements existants
    -- la référencent), mais on ne peut plus la choisir.
    active boolean NOT NULL DEFAULT true,

    CONSTRAINT formule_nom_unique UNIQUE (nom)
);

-- Les trois formules de départ. Les chiffres sont PROVISOIRES : c'est la
-- plateforme qui les change désormais, depuis son dashboard.
INSERT INTO formule (nom, nb_tontines_max, nb_membres_max, sms_par_mois, prix_mensuel, active)
VALUES ('DECOUVERTE', 1, 30, 100, 5000.00, true),
       ('PRO', 10, 200, 1000, 25000.00, true),
       ('MAX', 0, 0, 10000, 0.00, true);

-- 2) L'abonnement référence désormais la formule par sa clé.
ALTER TABLE abonnement ADD COLUMN formule_id bigint;

-- Migration des abonnements existants (aucun pour l'instant, mais la migration
-- doit être juste même en cas de rejeu sur une base déjà peuplée).
UPDATE abonnement
SET formule_id = f.id
FROM formule f
WHERE f.nom = abonnement.formule;

ALTER TABLE abonnement ALTER COLUMN formule_id SET NOT NULL;
ALTER TABLE abonnement DROP COLUMN formule;

ALTER TABLE abonnement
    ADD CONSTRAINT abonnement_formule_fk FOREIGN KEY (formule_id) REFERENCES formule (id);

-- 3) L'email devient OBLIGATOIRE pour les gestionnaires et les administrateurs
-- (ceux qui paient, et ceux qui administrent la plateforme). Les MEMBRES
-- l'ont toujours facultatif (beaucoup n'ont pas d'email).
--
-- NOT VALID : les lignes EXISTANTES ne sont pas vérifiées (2 gestionnaires
-- n'ont pas d'email aujourd'hui, on ne va pas les inventer), mais toute ligne
-- créée ou modifiée depuis doit respecter la règle. C'est le filet en base :
-- l'application peut avoir un bug, la base, non.
ALTER TABLE utilisateur
    ADD CONSTRAINT utilisateur_email_obligatoire_payeurs
    CHECK (role = 'MEMBRE' OR (email IS NOT NULL AND email <> '')) NOT VALID;
