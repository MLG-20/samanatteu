-- Le site public, piloté depuis le back-office de l'ADMIN :
--   1) parametre_site  : réseaux sociaux, coordonnées de contact, page « À propos » ;
--   2) message_contact : les messages envoyés par le formulaire de la page Contact.
--
-- Deux tables, car ce sont deux choses différentes : les paramètres tiennent en
-- UNE ligne (modifiée par l'ADMIN), les messages s'ajoutent (un par visiteur).

-- 1) Les paramètres du site.
--
-- UNE SEULE LIGNE, toujours : CHECK (id = 1) interdit d'en créer une deuxième.
-- Il n'y a donc jamais de question « quels paramètres s'appliquent ? ».
--
-- Une colonne vide (NULL) = rien à afficher : l'icône du réseau n'apparaît pas,
-- la ligne de contact non plus.
CREATE TABLE parametre_site (
    id bigint PRIMARY KEY CHECK (id = 1),

    -- Les réseaux sociaux : l'URL complète de la page.
    facebook character varying(255),
    instagram character varying(255),
    tiktok character varying(255),
    whatsapp character varying(255),
    linkedin character varying(255),
    youtube character varying(255),
    x character varying(255),

    -- La page Contact : les coordonnées affichées à côté du formulaire.
    contact_telephone character varying(20),
    contact_whatsapp character varying(20),
    contact_email character varying(255),
    contact_adresse character varying(255),
    contact_horaires character varying(255),

    -- La page À propos : une accroche et trois blocs.
    apropos_accroche character varying(255),
    apropos_histoire text,
    apropos_mission text,
    apropos_valeurs text,

    created_at timestamp without time zone,
    updated_at timestamp without time zone
);

