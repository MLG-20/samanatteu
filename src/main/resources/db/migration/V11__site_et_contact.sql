-- 2) Les messages du formulaire de contact.
--
-- Envoyés par un VISITEUR (pas de compte) : on ne les rattache donc à aucun
-- utilisateur. Il laisse un moyen de le recontacter : téléphone ou email
-- (au moins l'un des deux, vérifié par le CHECK).
CREATE TABLE message_contact (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom character varying(100) NOT NULL,
    telephone character varying(20),
    email character varying(255),
    sujet character varying(150) NOT NULL,
    message text NOT NULL,
    -- L'ADMIN le marque lu depuis son back-office.
    lu boolean NOT NULL DEFAULT false,
    created_at timestamp without time zone,
    updated_at timestamp without time zone,

    CONSTRAINT message_contact_moyen_de_reponse CHECK (telephone IS NOT NULL OR email IS NOT NULL)
);

-- La liste de l'ADMIN : les plus récents d'abord.
CREATE INDEX message_contact_created_at_idx ON message_contact (created_at DESC);
